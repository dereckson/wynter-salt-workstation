from datetime import date
from pathlib import Path
import re
import shutil
import sqlite3
import sys
from typing import List


#   -------------------------------------------------------------
#   Database path
#   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -


CANDIDATES_HISTORY_DB = [
    Path.home() / ".config/google-chrome-unstable/Default/History",
    Path.home() / ".config/google-chrome/Default/History",
]


def find_history_db() -> Path|None:
    for candidate in CANDIDATES_HISTORY_DB:
        if candidate.exists():
            return candidate

    return None


#   -------------------------------------------------------------
#   Database queries
#   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -


def extract_monthly_urls(db_path, month) -> List[str]:
    tmpfile = db_path.with_suffix(".tmp")
    shutil.copyfile(db_path, tmpfile)

    conn = sqlite3.connect(str(tmpfile))
    cursor = conn.cursor()

    # Why 11644473600? See https://stackoverflow.com/q/76855251/1930997
    query = f"""
SELECT
    DATE(last_visit_time/1000000-11644473600,'unixepoch') as visit_date,
    url, title
FROM urls
WHERE
    hidden=0
    AND visit_date BETWEEN '{month}-01' AND '{month}-31'
    AND url NOT LIKE '%pinterest.com%'
    AND url NOT LIKE '%google.com%'
    AND url NOT LIKE '%dereckson.be%'
    AND url NOT LIKE '%nasqueron.org%'
    AND url NOT LIKE '%youtube.com%'
    AND url NOT LIKE '%leonardo.ai%'
    AND url NOT LIKE '%adobe.com%' -- Firefly, color.adobe.com
ORDER BY visit_date ASC;
"""

    cursor.execute(query)
    urls = cursor.fetchall()

    conn.close()
    tmpfile.unlink()

    return urls


#   -------------------------------------------------------------
#   Calendar helper methods
