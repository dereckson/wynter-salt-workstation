RE_MONTH=r"\d{4}-(0[1-9]|1[0-2])"


def current():
    """
    Return the current month in YYYY-MM format.
    """
    return date.today().strftime("%Y-%m")


def is_valid_month(expression: str) -> bool:
    """
    Validate a month expression in YYYY-MM format.
    Accepts years 0000-9999 and months 01-12.
    """
    return bool(re.fullmatch(RE_MONTH, expression))


#   -------------------------------------------------------------
#   Application entry point
#   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -


def run(month: str):
    db_path = find_history_db()
    if db_path is None:
        print("Can't find Chrome history database", file=sys.stderr)
        sys.exit(2)

    urls = extract_monthly_urls(db_path, month)
    for url in urls:
        print(url)


if __name__ == "__main__":
    argc = len(sys.argv)

    if argc < 2:
        run(current())
        sys.exit(0)

    arg_month = sys.argv[1]

    if not is_valid_month(sys.argv[1]):
        print("Invalid month expression")
        sys.exit(1)

    run(arg_month)
